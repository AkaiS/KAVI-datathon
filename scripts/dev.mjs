// Writes config.js from .env, then serves the project folder as static files.
// Usage: npm run dev   (or: npm run config to only write config.js, e.g. before deploying)
import { createServer } from 'node:http';
import { readFile, writeFile } from 'node:fs/promises';
import { extname, join, normalize, resolve, sep } from 'node:path';

const root = resolve(import.meta.dirname, '..');

try {
  process.loadEnvFile(join(root, '.env'));
} catch {
  console.error('Missing .env. Run: cp .env.example .env  and fill in your Supabase values.');
  process.exit(1);
}

const { SUPABASE_URL, SUPABASE_PUBLISHABLE_KEY } = process.env;
if (!SUPABASE_URL || !SUPABASE_PUBLISHABLE_KEY) {
  console.error('.env must set SUPABASE_URL and SUPABASE_PUBLISHABLE_KEY.');
  process.exit(1);
}

const config = { SUPABASE_URL, SUPABASE_PUBLISHABLE_KEY };
await writeFile(
  join(root, 'config.js'),
  `// Generated by scripts/dev.mjs from .env. Do not edit or commit.\nwindow.APP_CONFIG = ${JSON.stringify(config, null, 2)};\n`
);
console.log('Wrote config.js');

if (process.argv.includes('--config-only')) process.exit(0);

const types = {
  '.html': 'text/html; charset=utf-8',
  '.js': 'text/javascript; charset=utf-8',
  '.mjs': 'text/javascript; charset=utf-8',
  '.css': 'text/css; charset=utf-8',
  '.json': 'application/json',
  '.svg': 'image/svg+xml',
  '.png': 'image/png',
};
const blocked = ['.env', '.git'];

const port = Number(process.env.PORT) || 5173;
createServer(async (req, res) => {
  const path = decodeURIComponent(new URL(req.url, 'http://localhost').pathname);
  const file = normalize(join(root, path === '/' ? 'index.html' : path));
  if (!file.startsWith(root + sep) || blocked.some((name) => file.split('/').includes(name))) {
    res.writeHead(404).end('Not found');
    return;
  }
  try {
    const body = await readFile(file);
    res.writeHead(200, { 'Content-Type': types[extname(file)] ?? 'application/octet-stream' }).end(body);
  } catch {
    res.writeHead(404).end('Not found');
  }
}).listen(port, () => console.log(`Serving on http://localhost:${port}`));
